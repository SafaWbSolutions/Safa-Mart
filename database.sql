create extension if not exists pg_trgm;
create extension if not exists pgcrypto;

-- ----------------------------------------------------------------------------
-- Products
-- ----------------------------------------------------------------------------
create table if not exists public.products (
    id                bigint generated by default as identity primary key,
    slug              text        not null,
    title             text        not null,
    description       text        not null default '',
    price             numeric(12,2) not null default 0,
    mrp               numeric(12,2) not null default 0,
    discount_percent  integer     not null default 0,
    category          text        not null default 'Other',
    source_platform   text        not null default 'Other',
    thumbnail_url     text,
    gallery_urls      jsonb       not null default '[]'::jsonb,
    affiliate_url     text        not null,
    original_url      text        not null,
    clicks            bigint      not null default 0,
    is_active         boolean     not null default true,
    last_checked_at   timestamptz,
    last_synced_at    timestamptz not null default now(),
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),
    constraint products_slug_key unique (slug),
    constraint products_original_url_key unique (original_url),
    constraint products_price_check check (price >= 0),
    constraint products_mrp_check check (mrp >= 0),
    constraint products_clicks_check check (clicks >= 0),
    constraint products_discount_check check (discount_percent between 0 and 100),
    constraint products_gallery_is_array check (jsonb_typeof(gallery_urls) = 'array')
);

-- Add columns introduced by later releases without failing on existing installs.
alter table public.products add column if not exists description text not null default '';
alter table public.products add column if not exists last_checked_at timestamptz;
alter table public.products add column if not exists brand text not null default '';
alter table public.products add column if not exists rating numeric(3,2) not null default 0;
alter table public.products add column if not exists rating_count integer not null default 0;
alter table public.products add column if not exists specs jsonb not null default '[]'::jsonb;

comment on table public.products is 'Affiliate product catalogue for Safa Mart.';
comment on column public.products.original_url is 'Canonical merchant URL; used as the upsert conflict target.';
comment on column public.products.affiliate_url is 'Final tracked affiliate URL opened by go.php.';
comment on column public.products.gallery_urls is 'JSON array of locally hosted WebP image URLs.';
comment on column public.products.last_checked_at is 'Last stock/price verification by the scheduled sync.';

-- ----------------------------------------------------------------------------
-- updated_at trigger
-- ----------------------------------------------------------------------------
create or replace function public.set_products_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists products_set_updated_at on public.products;
create trigger products_set_updated_at
before update on public.products
for each row
execute function public.set_products_updated_at();

-- ----------------------------------------------------------------------------
-- Keep the public product slug stable across re-syncs.
-- The scraper regenerates a random slug per run; without this trigger every
-- upsert would change the product URL and break shared/indexed links.
-- ----------------------------------------------------------------------------
create or replace function public.keep_products_slug()
returns trigger
language plpgsql
as $$
begin
    new.slug = old.slug;
    return new;
end;
$$;

drop trigger if exists products_keep_slug on public.products;
create trigger products_keep_slug
before update on public.products
for each row
execute function public.keep_products_slug();

-- ----------------------------------------------------------------------------
-- Click counter RPC (called by go.php with the public anon key)
-- ----------------------------------------------------------------------------
create or replace function public.increment_product_click(product_id bigint)
returns bigint
language sql
security definer
set search_path = public
as $$
    update public.products
       set clicks = clicks + 1
     where id = product_id
       and is_active = true
    returning clicks;
$$;

revoke all on function public.increment_product_click(bigint) from public;
grant execute on function public.increment_product_click(bigint) to anon, authenticated, service_role;

